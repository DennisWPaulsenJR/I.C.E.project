"use strict";
const assert = require("assert");
const temporal = require("../temporal-discourse-runtime");
let checks = 0;
const ok = (value) => { assert(value); checks++; };
const one = (model, type) => model.temporalExpressions.find((item) => item.expressionClass === type);
const relation = (model, type) => model.temporalRelations.find((item) => item.type === type);

const before = temporal.derive("John arrived before Mary left.", "before");
ok(relation(before, "BEFORE")?.relationStatus === "SOURCE_EXPRESSED_TEMPORAL_RELATION_CANDIDATE");
const after = temporal.derive("John arrived after Mary left.", "after");
ok(relation(after, "AFTER") && relation(after, "AFTER").temporalRelationId !== relation(before, "BEFORE").temporalRelationId);
const during = temporal.derive("John arrived during the meeting.", "during");
ok(relation(during, "DURING")?.objectiveChronologyPromoted === false);
const sequence = temporal.derive("John arrived. Mary left.", "sequence");
ok(sequence.temporalRelations.length === 0 && sequence.discourseRelations[0].type === "TEXTUAL_SEQUENCE");
const yesterday = temporal.derive("Yesterday John arrived.", "yesterday");
ok(one(yesterday, "RELATIVE_TIME_EXPRESSION").resolutionState === "UNRESOLVED" && one(yesterday, "RELATIVE_TIME_EXPRESSION").candidateTemporalSemantics.reason === "MISSING_TEMPORAL_ANCHOR");
const anchored = temporal.derive("Yesterday John arrived.", "anchored", { referenceTime: "2026-09-28" });
ok(one(anchored, "RELATIVE_TIME_EXPRESSION").candidateTemporalSemantics.candidateDate === "2026-09-27");
const thenAnchored = temporal.derive("Then John arrived.", "then-a", { discourseAnchor: "proposition-prior" });
ok(one(thenAnchored, "TEMPORAL_CONNECTIVE").candidateTemporalSemantics.exactTimestamp === null);
const thenOpen = temporal.derive("Then John arrived.", "then-b");
ok(one(thenOpen, "TEMPORAL_CONNECTIVE").resolutionState === "UNRESOLVED");
const march = temporal.derive("On March 3, John arrived.", "march");
ok(one(march, "ABSOLUTE_DATE_EXPRESSION").candidateTemporalSemantics.year === null);
const past = temporal.derive("John walked.", "past");
ok(one(past, "TENSE_TIME_CANDIDATE").candidateTemporalSemantics.orientation === "PAST_CANDIDATE");
const future = temporal.derive("John will arrive.", "future");
ok(one(future, "TENSE_TIME_CANDIDATE").candidateTemporalSemantics.orientation === "FUTURE_CANDIDATE");
const negative = temporal.derive("John did not arrive yesterday.", "negative");
ok(negative.propositions[0].polarity === "NEGATIVE" && one(negative, "RELATIVE_TIME_EXPRESSION"));
const question = temporal.derive("Did John arrive yesterday?", "question");
ok(question.propositions[0].status === "NON_ASSERTIVE_CONTENT");
const attributed = temporal.derive("Mary said John arrived yesterday.", "attributed");
ok(attributed.propositions[0].attributed === true && one(attributed, "RELATIVE_TIME_EXPRESSION"));
const sameDate = temporal.derive("John arrived on March 3. Mary left on March 3.", "same-date");
ok(sameDate.propositions.length === 2 && sameDate.authority.eventCreation === false);
const sameTime = temporal.derive("John arrived at noon. Mary left at noon.", "same-time");
ok(sameTime.propositions.length === 2 && sameTime.authority.eventCreation === false);
const ambiguous = temporal.derive("Yesterday John arrived, and Mary left.", "ambiguous");
ok(one(ambiguous, "RELATIVE_TIME_EXPRESSION").resolutionState === "UNRESOLVED");
const repeatA = temporal.derive("John arrived before Mary left.", "repeat");
const repeatB = temporal.derive("John arrived before Mary left.", "repeat");
ok(one(repeatA, "ORDERING_EXPRESSION").temporalExpressionId === one(repeatB, "ORDERING_EXPRESSION").temporalExpressionId);
ok(relation(repeatA, "BEFORE").temporalRelationId === relation(repeatB, "BEFORE").temporalRelationId);
ok(relation(before, "BEFORE").causalRelationCreated === false && before.authority.truthPromotion === false && before.authority.externalProviderCalls === 0);
console.log(`temporal discourse R34 QA passed ${JSON.stringify({ checks, fixtures: 17, deterministic: true, idempotent: true, network: 0 })}`);
