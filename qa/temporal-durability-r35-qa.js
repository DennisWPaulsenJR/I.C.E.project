"use strict";
const assert = require("assert");
const fs = require("fs");
const os = require("os");
const path = require("path");
const temporal = require("../temporal-discourse-runtime");
const durable = require("../temporal-durability-runtime");
let checks = 0;
const ok = (value) => { assert(value); checks++; };
const file = path.join(os.tmpdir(), `ice-r35-${process.pid}-${Date.now()}-${Math.random().toString(16).slice(2)}.sqlite`);
try {
  const before = temporal.derive("John arrived before Mary left.", "source-a");
  const relative = temporal.derive("Yesterday John arrived.", "source-relative", { referenceTime: "2026-09-28" });
  const missing = temporal.derive("Yesterday John arrived.", "source-missing");
  const attributed = temporal.derive("Mary said John arrived yesterday.", "source-attributed");
  const negative = temporal.derive("John did not arrive yesterday.", "source-negative");
  const question = temporal.derive("Did John arrive yesterday?", "source-question");
  const sequence = temporal.derive("John arrived. Mary left.", "source-sequence");
  let store = durable.open(file);
  [before, relative, missing, attributed, negative, question, sequence].forEach((model) => ok(durable.persist(model, { provider: store }).state === "DURABLY_PERSISTED"));
  ok(durable.persist(before, { provider: store }).replay === true);
  store.closePersistenceProvider();
  store = durable.open(file);
  const recoveredBefore = durable.recover({ provider: store, sourceScope: "source-a" });
  const originalRelation = before.temporalRelations[0];
  ok(recoveredBefore.expressions.some((item) => item.temporalExpressionId === before.temporalExpressions[0].temporalExpressionId));
  ok(recoveredBefore.relations[0].temporalRelationId === originalRelation.temporalRelationId && recoveredBefore.relations[0].type === "BEFORE");
  const recoveredRelative = durable.recover({ provider: store, sourceScope: "source-relative" }).expressions.find((item) => item.expressionClass === "RELATIVE_TIME_EXPRESSION");
  ok(recoveredRelative.anchorReference.value === "2026-09-28" && recoveredRelative.candidateTemporalSemantics.candidateDate === "2026-09-27");
  ok(durable.revalidate(recoveredRelative, { sourceScope: "source-relative" }).state === "REVALIDATED_CANDIDATE");
  const recoveredMissing = durable.recover({ provider: store, sourceScope: "source-missing" }).expressions.find((item) => item.expressionClass === "RELATIVE_TIME_EXPRESSION");
  ok(recoveredMissing.resolutionState === "UNRESOLVED" && recoveredMissing.candidateTemporalSemantics.reason === "MISSING_TEMPORAL_ANCHOR");
  ok(durable.recover({ provider: store, sourceScope: "source-attributed" }).expressions.some((item) => item.propositionContext.attributed === true));
  ok(durable.recover({ provider: store, sourceScope: "source-negative" }).expressions.some((item) => item.propositionContext.polarity === "NEGATIVE") && durable.recover({ provider: store, sourceScope: "source-question" }).expressions.some((item) => item.propositionContext.status === "NON_ASSERTIVE_CONTENT"));
  ok(durable.recover({ provider: store, sourceScope: "source-sequence" }).relations.length === 0);
  const after = temporal.derive("John arrived after Mary left.", "source-b");
  ok(durable.persist(after, { provider: store }).state === "DURABLY_PERSISTED");
  const contradiction = durable.govern({ provider: store, type: "CONTRADICTS", fromRecordId: originalRelation.temporalRelationId, toRecordId: after.temporalRelations[0].temporalRelationId, sourceScope: "comparison" });
  ok(contradiction.contradictionSelectsWinner === false && durable.recover({ provider: store }).relations.length >= 2);
  const qualified = durable.govern({ provider: store, type: "QUALIFIES", fromRecordId: originalRelation.temporalRelationId, toRecordId: after.temporalRelations[0].temporalRelationId, sourceScope: "comparison" });
  ok(qualified.originalMutated === false);
  const supersession = durable.govern({ provider: store, type: "SUPERSEDES", fromRecordId: originalRelation.temporalRelationId, toRecordId: after.temporalRelations[0].temporalRelationId, sourceScope: "source-a", authorizationRef: "controlled-r35-decision" });
  ok(supersession.predecessorDeleted === false);
  const authority = durable.setCurrentAuthority({ provider: store, recordId: after.temporalRelations[0].temporalRelationId, sourceScope: "source-a", use: "CONTROLLED_TEMPORAL_QUERY", authorizationRef: "controlled-r35-decision" });
  ok(authority.newestRecordRule === false && authority.currentAuthority === true);
  ok(durable.revalidate({ sourceScope: "x", anchorRequirement: "REFERENCE_TIME_REQUIRED", resolutionState: "RESOLVED_CANDIDATE" }).state === "REVALIDATION_REQUIRED");
  store.closePersistenceProvider();
  store = durable.open(file);
  const reopened = durable.recover({ provider: store });
  ok(reopened.governance.length === 3 && reopened.authorities.length === 1);
  ok(reopened.relations.some((item) => item.temporalRelationId === originalRelation.temporalRelationId));
  ok(reopened.expressions.every((item) => item.truthPromoted === false && item.eventCreated === false));
  store.closePersistenceProvider();
  console.log(`temporal durability R35 QA passed ${JSON.stringify({ checks, actualCloseReopen: true, replayDuplicates: 0, network: 0 })}`);
} finally { try { fs.unlinkSync(file); } catch (_) {} }
